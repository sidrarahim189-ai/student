import streamlit as st
import numpy as np
import pandas as pd

from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression

# ----------------------------------------------------------
# 1. Application configuration
# ----------------------------------------------------------

st.set_page_config(
    page_title="AI Student Predictor",
    page_icon="🎓",
    layout="centered"
)

st.title("🎓 AI Student Performance Predictor")

st.write(
    "Enter student academic information "
    "to predict the likelihood of passing."
)

st.info(
    "Educational demonstration only. "
    "The model uses synthetic data, not real student records."
)

# ----------------------------------------------------------
# 2. Generate a synthetic training dataset
# ----------------------------------------------------------

@st.cache_resource
def train_model():

    np.random.seed(42)

    number_of_students = 600

    mathematics = np.random.randint(
        20, 101, number_of_students
    )

    programming = np.random.randint(
        20, 101, number_of_students
    )

    statistics = np.random.randint(
        20, 101, number_of_students
    )

    attendance = np.random.randint(
        30, 101, number_of_students
    )

    # Generate an educational example target
    performance_score = (
        0.25 * mathematics +
        0.35 * programming +
        0.20 * statistics +
        0.20 * attendance
    )

    noise = np.random.normal(
        0, 8, number_of_students
    )

    passed = (
        performance_score + noise >= 50
    ).astype(int)

    # Prepare input features
    X = np.column_stack((
        mathematics,
        programming,
        statistics,
        attendance
    ))

    y = passed

    # Create and train the ML pipeline
    model = make_pipeline(
        StandardScaler(),
        LogisticRegression()
    )

    model.fit(X, y)

    return model


model = train_model()

# ----------------------------------------------------------
# 3. Collect student information
# ----------------------------------------------------------

st.header("Student Information")

student_name = st.text_input(
    "Student Name",
    "Student 01"
)

col1, col2 = st.columns(2)

with col1:

    mathematics = st.slider(
        "Mathematics",
        0, 100, 70
    )

    programming = st.slider(
        "Programming",
        0, 100, 75
    )

with col2:

    statistics = st.slider(
        "Statistics",
        0, 100, 65
    )

    attendance = st.slider(
        "Attendance (%)",
        0, 100, 85
    )

# ----------------------------------------------------------
# 4. Make AI prediction
# ----------------------------------------------------------

if st.button("Predict Student Performance"):

    input_data = np.array([[
        mathematics,
        programming,
        statistics,
        attendance
    ]])

    prediction = model.predict(input_data)[0]

    probabilities = model.predict_proba(
        input_data
    )[0]

    pass_probability = probabilities[1] * 100

    # ------------------------------------------------------
    # 5. Display prediction results
    # ------------------------------------------------------

    st.divider()

    st.subheader("Prediction Results")

    st.write("Student:", student_name)

    if prediction == 1:

        st.success("Prediction: Likely to Pass")

    else:

        st.warning("Prediction: At Risk of Failing")

    st.metric(
        "Estimated Pass Probability",
        f"{pass_probability:.2f}%"
    )

    st.progress(
        int(pass_probability)
    )

    # ------------------------------------------------------
    # 6. Display academic performance chart
    # ------------------------------------------------------

    st.subheader("Academic Performance")

    marks = pd.DataFrame({
        "Subject": [
            "Mathematics",
            "Programming",
            "Statistics",
            "Attendance"
        ],
        "Score": [
            mathematics,
            programming,
            statistics,
            attendance
        ]
    })

    st.bar_chart(
        marks.set_index("Subject")
    )

    st.caption(
        "The prediction is generated by a "
        "Logistic Regression model trained on "
        "synthetic educational data."
    )

# ----------------------------------------------------------
# End of application
